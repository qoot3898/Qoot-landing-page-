const dictionaries: Record<Lang, Strings> = { en: en as unknown as Strings, ar };

const STORE_KEY = 'qoot.admin.lang';

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(STORE_KEY);
    if (stored === 'ar' || stored === 'en') return stored;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'ar';
}

interface I18n {
  lang: Lang;
  t: Strings;
  dir: 'rtl' | 'ltr';
  setLang: (lang: Lang) => void;
  /** Picks the value for the interface language from a { ar, en } pair, falling back to the other. */
  pick: (value: Bilingual | null | undefined) => string;
  date: (iso: string | null | undefined, withTime?: boolean) => string;
  relative: (iso: string | null | undefined) => string;
  number: (n: number) => string;
  bytes: (n: number) => string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem(STORE_KEY, lang);
    } catch {
      /* storage unavailable */
    }
  }, [lang]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);

  const value = useMemo<I18n>(() => {
    const locale = lang === 'ar' ? 'ar-LY' : 'en-GB';
    const dateFmt = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric', numberingSystem: 'latn', timeZone: 'Africa/Tripoli' });
    const dateTimeFmt = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23', numberingSystem: 'latn', timeZone: 'Africa/Tripoli' });
    const numFmt = new Intl.NumberFormat(locale, { numberingSystem: 'latn' });
    const rel = new Intl.RelativeTimeFormat(locale, { numeric: 'auto', numberingSystem: 'latn' } as Intl.RelativeTimeFormatOptions);
    return {
      lang,
      t: dictionaries[lang],
      dir: lang === 'ar' ? 'rtl' : 'ltr',
      setLang,
      pick: (v) => (v ? (lang === 'ar' ? v.ar || v.en : v.en || v.ar) : ''),
      date: (iso, withTime = false) => {
        if (!iso) return '';
        const d = new Date(iso);
        return Number.isNaN(d.getTime()) ? '' : (withTime ? dateTimeFmt : dateFmt).format(d);
      },
      relative: (iso) => {
        if (!iso) return '';
        const d = new Date(iso);
        if (Number.isNaN(d.getTime())) return '';
        const seconds = (d.getTime() - Date.now()) / 1000;
        const abs = Math.abs(seconds);
        if (abs < 60) return rel.format(Math.round(seconds), 'second');
        if (abs < 3600) return rel.format(Math.round(seconds / 60), 'minute');
        if (abs < 86400) return rel.format(Math.round(seconds / 3600), 'hour');
        if (abs < 86400 * 7) return rel.format(Math.round(seconds / 86400), 'day');
        return dateFmt.format(d);
      },
      number: (n) => numFmt.format(n),
      bytes: (n) => {
        if (n < 1024) return `${numFmt.format(n)} B`;
        if (n < 1024 * 1024) return `${numFmt.format(Math.round(n / 1024))} KB`;
        return `${new Intl.NumberFormat(locale, { maximumFractionDigits: 1, numberingSystem: 'latn' }).format(n / 1024 / 1024)} MB`;
      },
    };
  }, [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const value = useContext(Ctx);
  if (!value) throw new Error('useI18n outside I18nProvider');
  return value;
}

